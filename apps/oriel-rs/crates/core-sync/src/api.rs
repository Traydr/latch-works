//! Pane View's sync API, as `remote-api.ts` and `remote-snapshot.ts` call it, on `reqwest`.
//!
//! The request and response types in [`types`] are generated at compile time from
//! `conformance/lockstep-core/api-schema.json`, which lockstep-core's `api-schema.test.ts` writes
//! from its zod schemas. A change on the TypeScript side changes that file, its Vitest suite fails
//! until the file is rewritten, and the rewrite changes these types, so the two clients cannot
//! drift apart unnoticed.
//!
//! Every call must run on the tokio thread (`oriel_runtime::TokioRuntime`).

use std::path::Path;
use std::sync::{Arc, Mutex, PoisonError};
use std::time::Duration;

use anyhow::{Context as _, anyhow, bail};
use futures::{FutureExt as _, StreamExt as _};
use oriel_core_index::RemoteEntrySnapshot;
use oriel_runtime::{CancelToken, Cancelled};
use reqwest::header::{CONTENT_LENGTH, CONTENT_TYPE, HeaderMap, HeaderName, HeaderValue};
use reqwest::{Client, Url};
use serde::Serialize;
use serde::de::DeserializeOwned;
use sha2::{Digest as _, Sha256};

/// The types lockstep-core's zod schemas describe, generated by typify.
#[allow(clippy::all, clippy::pedantic, missing_docs)]
pub mod types {
    typify::import_types!(
        schema = "../../conformance/lockstep-core/api-schema.json",
        derives = [PartialEq]
    );
}

/// How long run creation may still take once the run is cancelled: it cannot be aborted outright,
/// since only the id it returns lets the run be finalized.
const CREATE_SYNC_RUN_CANCEL_GRACE: Duration = Duration::from_secs(10);

/// The waits between finalization attempts; Pane View accepts an exact replay of an outcome.
const FINALIZE_RETRY_DELAYS: [Duration; 2] = [Duration::from_millis(250), Duration::from_secs(1)];

/// How often an upload or a hash reports its bytes.
pub(crate) const PROGRESS_INTERVAL: Duration = Duration::from_millis(100);

/// Read size for uploads, as Node's `createReadStream`.
const READ_CHUNK: usize = 64 * 1024;

/// The server a profile syncs to: its URL and its sync token.
#[derive(Clone, PartialEq, Eq)]
pub struct ApiTarget {
    pub url: String,
    pub token: String,
}

impl std::fmt::Debug for ApiTarget {
    // The token never reaches a log.
    fn fmt(&self, f: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        f.debug_struct("ApiTarget")
            .field("url", &self.url)
            .finish_non_exhaustive()
    }
}

/// A client for one Pane View server.
#[derive(Clone, Debug)]
pub struct PaneViewClient {
    http: Client,
    target: ApiTarget,
}

impl PaneViewClient {
    pub fn new(target: ApiTarget) -> anyhow::Result<Self> {
        Url::parse(&target.url)
            .with_context(|| format!("The Pane View URL {} is not a URL.", target.url))?;
        let http = Client::builder()
            .build()
            .context("starting the HTTP client")?;
        Ok(Self { http, target })
    }

    pub fn target(&self) -> &ApiTarget {
        &self.target
    }

    /// `new URL(route, apiUrl)`: an absolute route replaces the URL's path.
    fn url(&self, route: &str) -> anyhow::Result<Url> {
        Ok(Url::parse(&self.target.url)?.join(route)?)
    }

    /// `fetchRemoteSnapshot`: every entry Pane View's library holds.
    pub async fn fetch_snapshot(
        &self,
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<Vec<RemoteEntrySnapshot>> {
        let url = self.url("/api/sync/snapshot")?;
        let origin = url.origin().ascii_serialization();
        let request = self.http.get(url).bearer_auth(&self.target.token).send();
        let response = until_cancelled(cancel, request).await?.map_err(|error| {
            anyhow!(
                "Could not reach Pane View at {origin}: {}",
                network_reason(&error)
            )
        })?;
        let status = response.status();
        let text = until_cancelled(cancel, response.text()).await??;
        if !status.is_success() {
            bail!("/api/sync/snapshot failed with {}: {text}", status.as_u16());
        }
        let entries = match read_snapshot_entries(&text) {
            Some(entries) => entries,
            None => snapshot_entries_by_value(&text)?,
        };
        Ok(entries
            .into_iter()
            .map(|entry| RemoteEntrySnapshot {
                path: entry.path,
                sha256: entry.sha256,
                size: entry.size.max(0.0) as u64,
            })
            .collect())
    }

    /// `postJson`: a POST of `body`, read back as `R`. A status that is not 2xx fails with the
    /// server's text, as `${route} failed with ${status}: ${text}`.
    async fn post<B: Serialize, R: DeserializeOwned>(
        &self,
        route: &str,
        body: &B,
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<R> {
        let mut json = serde_json::to_value(body)?;
        write_whole_numbers_as_integers(&mut json);
        let request = self
            .http
            .post(self.url(route)?)
            .bearer_auth(&self.target.token)
            .json(&json)
            .send();
        let response = until_cancelled(cancel, request)
            .await?
            .with_context(|| format!("{route} failed"))?;
        let status = response.status();
        let text = until_cancelled(cancel, response.text()).await??;
        if !status.is_success() {
            bail!("{route} failed with {}: {text}", status.as_u16());
        }
        serde_json::from_str(&text).with_context(|| format!("{route} answered with {text}"))
    }

    /// `createSyncRun`. A cancel does not abort the request, since the server may already have
    /// made the run; it gets ten more seconds to answer with the id, so the run can be finalized
    /// as cancelled.
    pub async fn create_sync_run(
        &self,
        body: &types::CreateSyncRunRequest,
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<String> {
        let request = self.post::<_, types::SyncRun>("/api/sync/runs", body, None);
        let graced = async {
            match cancel {
                Some(cancel) => {
                    cancel.cancelled().await;
                    tokio::time::sleep(CREATE_SYNC_RUN_CANCEL_GRACE).await;
                }
                None => futures::future::pending::<()>().await,
            }
        };
        futures::select_biased! {
            created = Box::pin(request).fuse() => Ok(created?.sync_run_id),
            () = Box::pin(graced).fuse() => Err(anyhow!(
                "Cancelled while Pane View was still creating the sync run, so it may be left \
                 running. If Pane View's management page shows it running, cancel it there."
            )),
        }
    }

    /// `finalizeSyncRun`: records the run's outcome, trying three times so a brief outage does
    /// not leave it running. It is never cancelled. Returns the last error when all failed.
    pub async fn finalize_sync_run(
        &self,
        sync_run_id: &str,
        body: &types::CompleteSyncRunRequest,
        on_retry: impl Fn(&anyhow::Error),
    ) -> Option<anyhow::Error> {
        let route = format!("/api/sync/runs/{sync_run_id}/complete");
        let mut last_error = None;
        for retry in FINALIZE_RETRY_DELAYS.iter().map(Some).chain([None]) {
            match self.post::<_, serde_json::Value>(&route, body, None).await {
                Ok(_) => return None,
                Err(error) => {
                    let Some(delay) = retry else {
                        last_error = Some(error);
                        break;
                    };
                    on_retry(&error);
                    last_error = Some(error);
                    tokio::time::sleep(*delay).await;
                }
            }
        }
        last_error
    }

    /// `POST /api/sync/upload-url`: where to put a file's bytes, signed for its size and hash.
    pub async fn upload_url(
        &self,
        body: &types::UploadUrlRequest,
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<types::UploadTarget> {
        self.post("/api/sync/upload-url", body, cancel).await
    }

    /// `POST /api/sync/complete-object`: records an uploaded file in the library.
    pub async fn complete_object(
        &self,
        body: &types::CompleteObjectRequest,
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<()> {
        self.post::<_, serde_json::Value>("/api/sync/complete-object", body, cancel)
            .await
            .map(drop)
    }

    /// `deleteRemoteItem`: removes a path from the library.
    pub async fn delete_object(
        &self,
        logical_path: &str,
        sync_run_id: &str,
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<()> {
        let body = types::DeleteObjectRequest {
            action: "delete".to_owned(),
            logical_path: logical_path.to_owned(),
            sync_run_id: sync_run_id.to_owned(),
        };
        self.post::<_, serde_json::Value>("/api/sync/complete-object", &body, cancel)
            .await
            .map(drop)
    }

    /// `uploadFile`: PUTs the file to the signed URL with the headers Pane View signed (its
    /// length and its SHA-256, plan 026), hashing the bytes as they go out. The upload fails if
    /// the file's size changed, if a different number of bytes went out, or if they hash to
    /// anything but `expected_sha256`.
    #[allow(clippy::too_many_arguments)]
    pub async fn upload_file(
        &self,
        upload_url: &str,
        headers: &std::collections::HashMap<String, String>,
        file_path: &Path,
        content_type: &str,
        expected_sha256: &str,
        expected_size: u64,
        on_progress: &(dyn Fn(u64, u64) + Send + Sync),
        cancel: Option<&CancelToken>,
    ) -> anyhow::Result<()> {
        // `stat`, then `open`, as `uploadFile` does, on one blocking thread.
        let (total, file) = {
            let path = file_path.to_owned();
            tokio::task::spawn_blocking(move || {
                let size = std::fs::metadata(&path)?.len();
                if size != expected_size {
                    return Ok((size, None));
                }
                std::io::Result::Ok((size, Some(std::fs::File::open(&path)?)))
            })
            .await??
        };
        let Some(file) = file else {
            bail!("File changed during sync; retry this item.");
        };

        let mut header_map = HeaderMap::new();
        for (name, value) in headers {
            header_map.insert(
                HeaderName::from_bytes(name.as_bytes())
                    .with_context(|| format!("Pane View signed a bad header name {name}"))?,
                HeaderValue::from_str(value)
                    .with_context(|| format!("Pane View signed a bad value for {name}"))?,
            );
        }
        if !header_map.contains_key(CONTENT_LENGTH) {
            header_map.insert(CONTENT_LENGTH, HeaderValue::from(total));
        }
        if !header_map.contains_key(CONTENT_TYPE) {
            header_map.insert(CONTENT_TYPE, HeaderValue::from_str(content_type)?);
        }

        let tally = Arc::new(Mutex::new(Tally {
            bytes: 0,
            digest: Sha256::new(),
            read_error: None,
        }));
        // A blocking thread reads the file and hashes it, a few chunks ahead of the socket, so
        // neither the reads nor the hashing wait their turn on the tokio thread. Each chunk
        // comes with the hash of the file up to its end, and counts, with its hash, once the
        // request takes it: the tally is what went out, as when the request read the file.
        let (chunks, received) = tokio::sync::mpsc::channel(READ_AHEAD);
        tokio::task::spawn_blocking(move || read_ahead(file, &chunks));
        let stream = futures::stream::unfold(
            (received, tally.clone()),
            |(mut received, tally)| async move {
                let chunk = match received.recv().await? {
                    Ok((chunk, digest)) => {
                        let mut tally = tally.lock().unwrap_or_else(PoisonError::into_inner);
                        tally.bytes += chunk.len() as u64;
                        tally.digest = digest;
                        Ok(chunk)
                    }
                    Err(error) => {
                        let message = error.to_string();
                        tally
                            .lock()
                            .unwrap_or_else(PoisonError::into_inner)
                            .read_error = Some(error);
                        Err(std::io::Error::other(message))
                    }
                };
                Some((chunk, (received, tally)))
            },
        );
        // Progress is read off the tally while the body streams, at most every 100 ms.
        let progress_tally = tally.clone();
        let reporting = async move {
            loop {
                tokio::time::sleep(PROGRESS_INTERVAL).await;
                let bytes = progress_tally
                    .lock()
                    .unwrap_or_else(PoisonError::into_inner)
                    .bytes;
                on_progress(bytes, total);
            }
        };

        let request = self
            .http
            .put(upload_url)
            .headers(header_map)
            .body(reqwest::Body::wrap_stream(stream.boxed()))
            .send();
        let sent = futures::select_biased! {
            sent = Box::pin(until_cancelled(cancel, request)).fuse() => sent,
            () = Box::pin(reporting).fuse() => unreachable!("progress reports never end"),
        };
        let take_read_error = || {
            tally
                .lock()
                .unwrap_or_else(PoisonError::into_inner)
                .read_error
                .take()
        };
        let response = match sent {
            Err(cancelled) => return Err(cancelled),
            Ok(Err(error)) => {
                // A read error (a drive unplugged, the file gone) is what the user sees, not the
                // request's generic failure.
                return Err(match take_read_error() {
                    Some(read_error) => read_error.into(),
                    None => anyhow::Error::new(error).context("Upload failed"),
                });
            }
            Ok(Ok(response)) => response,
        };
        let status = response.status();
        if !status.is_success() {
            let text = until_cancelled(cancel, response.text())
                .await?
                .unwrap_or_default();
            bail!("Upload failed with {}: {text}", status.as_u16());
        }
        if let Some(read_error) = take_read_error() {
            return Err(read_error.into());
        }
        let (bytes, digest) = {
            let mut tally = tally.lock().unwrap_or_else(PoisonError::into_inner);
            (tally.bytes, std::mem::take(&mut tally.digest).finalize())
        };
        if bytes != expected_size {
            bail!("Uploaded byte count does not match declared size.");
        }
        let uploaded: String = digest.iter().map(|byte| format!("{byte:02x}")).collect();
        if uploaded != expected_sha256.to_ascii_lowercase() {
            bail!("Uploaded bytes do not match declared sha256.");
        }
        on_progress(total, total);
        Ok(())
    }
}

/// Chunks read ahead of an upload's socket.
const READ_AHEAD: usize = 4;

/// A chunk of an upload, with the hash of the file from its start to the chunk's end.
type ReadChunk = std::io::Result<(Vec<u8>, Sha256)>;

/// Reads `file` to its end, or to its first error, in `READ_CHUNK`s for an upload, until the
/// upload stops taking them.
fn read_ahead(mut file: std::fs::File, chunks: &tokio::sync::mpsc::Sender<ReadChunk>) {
    use std::io::Read as _;
    let mut digest = Sha256::new();
    loop {
        let mut buffer = vec![0; READ_CHUNK];
        let chunk = match file.read(&mut buffer) {
            Ok(0) => return,
            Ok(read) => {
                buffer.truncate(read);
                digest.update(&buffer);
                Ok((buffer, digest.clone()))
            }
            Err(error) => Err(error),
        };
        let failed = chunk.is_err();
        if chunks.blocking_send(chunk).is_err() || failed {
            return;
        }
    }
}

/// What an upload has read so far.
struct Tally {
    bytes: u64,
    digest: Sha256,
    read_error: Option<std::io::Error>,
}

/// Runs `future` unless `cancel` fires first, which drops it (aborting a request) and fails with
/// [`Cancelled`].
pub(crate) async fn until_cancelled<F: std::future::Future>(
    cancel: Option<&CancelToken>,
    future: F,
) -> anyhow::Result<F::Output> {
    let Some(cancel) = cancel else {
        return Ok(future.await);
    };
    if cancel.is_cancelled() {
        return Err(Cancelled.into());
    }
    futures::select_biased! {
        () = Box::pin(cancel.cancelled()).fuse() => Err(Cancelled.into()),
        output = Box::pin(future).fuse() => Ok(output),
    }
}

/// The generated types hold JSON numbers as `f64`, which serde writes as `5.0`; JavaScript
/// writes `5`. Pane View reads either, but the bodies should be the ones lockstep-core sends.
fn write_whole_numbers_as_integers(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Number(number) => {
            if let Some(float) = number.as_f64().filter(|float| {
                float.fract() == 0.0 && float.abs() < 9_007_199_254_740_992.0 && !number.is_i64()
            }) {
                *value = serde_json::Value::from(float as i64);
            }
        }
        serde_json::Value::Array(items) => {
            items.iter_mut().for_each(write_whole_numbers_as_integers)
        }
        serde_json::Value::Object(fields) => {
            fields
                .values_mut()
                .for_each(write_whole_numbers_as_integers);
        }
        _ => {}
    }
}

/// Why a request never reached the server, as undici's cause would put it (`ECONNREFUSED`…).
fn network_reason(error: &reqwest::Error) -> String {
    let mut source: Option<&dyn std::error::Error> = std::error::Error::source(error);
    let mut deepest = None;
    while let Some(cause) = source {
        deepest = Some(cause.to_string());
        source = cause.source();
    }
    deepest.unwrap_or_else(|| error.to_string())
}

/// A snapshot's entries read straight from the response, as [`snapshot_entries_by_value`] reads
/// them; `None` for any body it might read otherwise or refuse, which it then reads. Only an
/// object with one `entries` array of well-formed entries reads this way.
fn read_snapshot_entries(text: &str) -> Option<Vec<types::RemoteEntry>> {
    struct Body(Vec<types::RemoteEntry>);

    impl<'de> serde::Deserialize<'de> for Body {
        fn deserialize<D: serde::Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
            struct BodyVisitor;
            impl<'de> serde::de::Visitor<'de> for BodyVisitor {
                type Value = Body;
                fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                    formatter.write_str("a snapshot response")
                }
                fn visit_map<A: serde::de::MapAccess<'de>>(
                    self,
                    mut map: A,
                ) -> Result<Body, A::Error> {
                    let mut entries = None;
                    while let Some(key) = map.next_key::<std::borrow::Cow<'de, str>>()? {
                        if key == "entries" {
                            if entries.is_some() {
                                return Err(serde::de::Error::duplicate_field("entries"));
                            }
                            entries = Some(map.next_value()?);
                        } else {
                            map.next_value::<serde::de::IgnoredAny>()?;
                        }
                    }
                    entries
                        .map(Body)
                        .ok_or_else(|| serde::de::Error::missing_field("entries"))
                }
            }
            deserializer.deserialize_map(BodyVisitor)
        }
    }

    serde_json::from_str::<Body>(text).ok().map(|body| body.0)
}

/// `fetchRemoteSnapshot`'s checks, through a JSON value: the entries, or why the body is refused.
fn snapshot_entries_by_value(text: &str) -> anyhow::Result<Vec<types::RemoteEntry>> {
    let body: serde_json::Value = serde_json::from_str(text)
        .context("Remote sync snapshot response must include an entries array.")?;
    let entries = body
        .get("entries")
        .and_then(serde_json::Value::as_array)
        .ok_or_else(|| anyhow!("Remote sync snapshot response must include an entries array."))?;
    entries
        .iter()
        .map(|entry| {
            serde_json::from_value(entry.clone())
                .map_err(|_| anyhow!("Remote snapshot entries must include path and size."))
        })
        .collect()
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The direct read takes only bodies the value read takes, with the same entries.
    #[test]
    fn reads_a_snapshot_directly_only_as_the_value_read_would() {
        let entry = r#"{"path":"a/b.jpg","size":3,"sha256":"ab","mtimeMs":1}"#;
        let bodies = [
            format!(r#"{{"entries":[{entry},{{"path":"c\u002fd.jpg","size":4.5}}],"status":"x"}}"#),
            r#"{"entries":[]}"#.to_owned(),
            format!(r#"{{"entries":[{entry}],"entries":[]}}"#),
            format!(r#"[[{entry}]]"#),
            r#"{"entries":{}}"#.to_owned(),
            r#"{"status":"database"}"#.to_owned(),
            r#"{"entries":[{"path":"a.jpg"}]}"#.to_owned(),
            r#"{"entries":[{"path":"a.jpg","size":"3"}]}"#.to_owned(),
            "<html>".to_owned(),
        ];
        let mut direct = 0;
        for body in &bodies {
            let by_value = snapshot_entries_by_value(body).map_err(|error| error.to_string());
            if let Some(entries) = read_snapshot_entries(body) {
                direct += 1;
                assert_eq!(Ok(entries), by_value, "{body}");
            }
        }
        assert_eq!(direct, 2, "the well-formed bodies read directly");
    }
}
