/// Chunks read ahead of an upload's socket.
const READ_AHEAD: usize = 4;

/// A chunk of an upload, with the hash of the file from its start to the chunk's end.
type ReadChunk = std::io::Result<(Vec<u8>, Sha256)>;

/// Reads `file` to its end, or to its first error, in `READ_CHUNK`s for an upload, until the
/// upload stops taking them.
fn read_ahead(mut file: std::fs::File, chunks: &tokio::sync::mpsc::Sender<ReadChunk>) {
    use std::io::Read as _;
    let mut digest = Sha256::new();
    loop {
        let mut buffer = vec![0; READ_CHUNK];
        let chunk = match file.read(&mut buffer) {
            Ok(0) => return,
            Ok(read) => {
                buffer.truncate(read);
                digest.update(&buffer);
                Ok((buffer, digest.clone()))
            }
            Err(error) => Err(error),
        };
        let failed = chunk.is_err();
        if chunks.blocking_send(chunk).is_err() || failed {
            return;
        }
    }
}

/// What an upload has read so far.
struct Tally {
    bytes: u64,
    digest: Sha256,
    read_error: Option<std::io::Error>,
}

/// Runs `future` unless `cancel` fires first, which drops it (aborting a request) and fails with
/// [`Cancelled`].
pub(crate) async fn until_cancelled<F: std::future::Future>(
    cancel: Option<&CancelToken>,
    future: F,
) -> anyhow::Result<F::Output> {
    let Some(cancel) = cancel else {
        return Ok(future.await);
    };
    if cancel.is_cancelled() {
        return Err(Cancelled.into());
    }
    futures::select_biased! {
        () = Box::pin(cancel.cancelled()).fuse() => Err(Cancelled.into()),
        output = Box::pin(future).fuse() => Ok(output),
    }
}

/// A request body as JSON. The generated types hold JSON numbers as `f64`, which serde writes as
/// `5.0`; JavaScript writes `5`. Pane View reads either, but the bodies should be the ones
/// lockstep-core sends.
pub(crate) fn json_body(body: &impl Serialize) -> serde_json::Result<serde_json::Value> {
    let mut json = serde_json::to_value(body)?;
    write_whole_numbers_as_integers(&mut json);
    Ok(json)
}

fn write_whole_numbers_as_integers(value: &mut serde_json::Value) {
    match value {
        serde_json::Value::Number(number) => {
            if let Some(integer) = number
                .as_f64()
                .filter(|_| !number.is_i64())
                .and_then(oriel_core_domain::number::js_integer)
            {
                *value = serde_json::Value::from(integer);
            }
        }
        serde_json::Value::Array(items) => {
            items.iter_mut().for_each(write_whole_numbers_as_integers)
        }
        serde_json::Value::Object(fields) => {
            fields
                .values_mut()
                .for_each(write_whole_numbers_as_integers);
        }
        _ => {}
    }
}

/// Why a request never reached the server. A refused connection reads as undici's cause does
/// (`connect ECONNREFUSED 127.0.0.1:3000`), anything else as its deepest cause.
fn network_reason(error: &reqwest::Error) -> String {
    let mut source: Option<&dyn std::error::Error> = std::error::Error::source(error);
    let mut deepest = None;
    while let Some(cause) = source {
        if let Some(io) = cause.downcast_ref::<std::io::Error>()
            && io.kind() == std::io::ErrorKind::ConnectionRefused
            && let Some(address) = error.url().and_then(socket_address)
        {
            return format!("connect ECONNREFUSED {address}");
        }
        deepest = Some(cause.to_string());
        source = cause.source();
    }
    deepest.unwrap_or_else(|| error.to_string())
}

/// `host:port` as Node writes a socket address, an IPv6 host without its brackets.
fn socket_address(url: &reqwest::Url) -> Option<String> {
    let host = url
        .host_str()?
        .trim_start_matches('[')
        .trim_end_matches(']');
    Some(format!("{host}:{}", url.port_or_known_default()?))
}

const NO_ENTRIES: &str = "Remote sync snapshot response must include an entries array.";
const BAD_ENTRY: &str = "Remote snapshot entries must include path and size.";

/// `RemoteSnapshotResponseSchema`: a snapshot answer's entries, read in one pass straight into
/// them. Fields it does not know are ignored and a hash that is not a string is dropped
/// (`.catch(undefined)`). Unlike zod, an entry written as an array or with a key named twice is
/// read rather than refused; Pane View writes neither.
pub(crate) fn parse_snapshot(text: &str) -> anyhow::Result<Vec<RemoteEntrySnapshot>> {
    let in_entry = Cell::new(false);
    let mut reader = serde_json::Deserializer::from_str(text);
    let read = Snapshot(&in_entry)
        .deserialize(&mut reader)
        .and_then(|entries| reader.end().map(|()| entries));
    match read {
        Ok(Some(entries)) => Ok(entries),
        Err(error) if in_entry.get() && error.is_data() => bail!(BAD_ENTRY),
        _ => bail!(NO_ENTRIES),
    }
}

#[derive(Deserialize)]
struct Entry {
    path: String,
    size: f64,
    #[serde(default, deserialize_with = "string_or_nothing")]
    sha256: Option<String>,
}

/// A string, or `None` for any other value, which is read past.
fn string_or_nothing<'de, D: Deserializer<'de>>(
    deserializer: D,
) -> Result<Option<String>, D::Error> {
    struct AnyValue;

    impl<'de> Visitor<'de> for AnyValue {
        type Value = Option<String>;

        fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
            formatter.write_str("any JSON value")
        }

        fn visit_str<E>(self, value: &str) -> Result<Self::Value, E> {
            Ok(Some(value.to_owned()))
        }

        fn visit_bool<E>(self, _: bool) -> Result<Self::Value, E> {
            Ok(None)
        }

        fn visit_unit<E>(self) -> Result<Self::Value, E> {
            Ok(None)
        }

        fn visit_i64<E>(self, _: i64) -> Result<Self::Value, E> {
            Ok(None)
        }

        fn visit_u64<E>(self, _: u64) -> Result<Self::Value, E> {
            Ok(None)
        }

        fn visit_f64<E>(self, _: f64) -> Result<Self::Value, E> {
            Ok(None)
        }

        fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
            while seq.next_element::<IgnoredAny>()?.is_some() {}
            Ok(None)
        }

        fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
            while map.next_entry::<IgnoredAny, IgnoredAny>()?.is_some() {}
            Ok(None)
        }
    }

    deserializer.deserialize_any(AnyValue)
}

/// The answer's top level: its entries, if it has an `entries` key. The flag says whether a
/// failure came from inside an entry.
struct Snapshot<'a>(&'a Cell<bool>);

impl<'de> DeserializeSeed<'de> for Snapshot<'_> {
    type Value = Option<Vec<RemoteEntrySnapshot>>;

    fn deserialize<D: Deserializer<'de>>(self, deserializer: D) -> Result<Self::Value, D::Error> {
        deserializer.deserialize_map(self)
    }
}

impl<'de> Visitor<'de> for Snapshot<'_> {
    type Value = Option<Vec<RemoteEntrySnapshot>>;

    fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("a snapshot response")
    }

    fn visit_map<A: MapAccess<'de>>(self, mut map: A) -> Result<Self::Value, A::Error> {
        let mut entries = None;
        while let Some(key) = map.next_key::<Key>()? {
            match key {
                Key::Entries => entries = Some(map.next_value_seed(Entries(self.0))?),
                Key::Other => {
                    map.next_value::<IgnoredAny>()?;
                }
            }
        }
        Ok(entries)
    }
}

struct Entries<'a>(&'a Cell<bool>);

impl<'de> DeserializeSeed<'de> for Entries<'_> {
    type Value = Vec<RemoteEntrySnapshot>;

    fn deserialize<D: Deserializer<'de>>(self, deserializer: D) -> Result<Self::Value, D::Error> {
        deserializer.deserialize_seq(self)
    }
}

impl<'de> Visitor<'de> for Entries<'_> {
    type Value = Vec<RemoteEntrySnapshot>;

    fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str("an array of entries")
    }

    fn visit_seq<A: SeqAccess<'de>>(self, mut seq: A) -> Result<Self::Value, A::Error> {
        let mut entries = Vec::new();
        loop {
            match seq.next_element::<Entry>() {
                Ok(Some(entry)) => entries.push(RemoteEntrySnapshot {
                    path: entry.path,
                    sha256: entry.sha256,
                    size: entry.size as u64,
                }),
                Ok(None) => return Ok(entries),
                Err(error) => {
                    self.0.set(true);
                    return Err(error);
                }
            }
        }
    }
}

/// A key of the answer's top level, compared without being copied.
enum Key {
    Entries,
    Other,
}

impl<'de> Deserialize<'de> for Key {
    fn deserialize<D: Deserializer<'de>>(deserializer: D) -> Result<Self, D::Error> {
        struct KeyVisitor;

        impl Visitor<'_> for KeyVisitor {
            type Value = Key;

            fn expecting(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
                formatter.write_str("a key")
            }

            fn visit_str<E>(self, key: &str) -> Result<Key, E> {
                Ok(if key == "entries" {
                    Key::Entries
                } else {
                    Key::Other
                })
            }
        }

        deserializer.deserialize_identifier(KeyVisitor)
    }
}
